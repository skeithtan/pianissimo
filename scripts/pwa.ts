/**
 * Build-time half of the offline support (DECISIONS U84), a Vite plugin with no dependency. Once
 * `vite build` has written the output directory, `writeServiceWorker` lists every file of the
 * build with its SHA-256 (source maps, Vite's `.vite/` manifest and the worker itself excepted),
 * stamps `index.html` with the build's content hash (`<meta name="pianissimo-build">`, which the
 * page reports to the worker) and writes `sw.js` from `src/workers/sw.ts` with that list.
 *
 * The build hash covers every precached file, so any change to the deploy gives a new worker,
 * cache and stamp, and an identical rebuild gives byte-identical output (no update at all).
 */
import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join, relative, resolve, sep } from 'node:path'
import { transformWithOxc, type Plugin } from 'vite'

export const BUILD_META_NAME = 'pianissimo-build'
const STAMP = new RegExp(`\\n\\s*<meta name="${BUILD_META_NAME}" content="[^"]*">`)

export interface ServiceWorkerReport {
  /** The build hash: the stamp in index.html and the suffix of the cache name. */
  readonly build: string
  readonly files: number
  readonly bytes: number
}

/** Precached: every file but source maps, Vite's own manifest and the worker script. */
export function isPrecached(path: string): boolean {
  return !path.endsWith('.map') && !path.startsWith('.vite/') && path !== 'sw.js'
}

/** Subresource Integrity string, as `fetch(url, { integrity })` checks it. */
export function integrityOf(bytes: Uint8Array): string {
  return `sha256-${createHash('sha256').update(bytes).digest('base64')}`
}

async function listFiles(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { recursive: true, withFileTypes: true })
  return entries
    .filter((entry) => entry.isFile())
    .map((entry) => relative(dir, join(entry.parentPath, entry.name)).split(sep).join('/'))
}

/**
 * Stamp `outDir/index.html` and write `outDir/sw.js`. Safe to run again over the same output
 * (the old stamp is replaced), which is how the e2e spec fakes a new deploy.
 */
export async function writeServiceWorker(root: string, outDir: string): Promise<ServiceWorkerReport> {
  const paths = (await listFiles(outDir)).filter(isPrecached).sort()
  if (!paths.includes('index.html')) throw new Error(`No index.html in ${outDir}`)
  const html = (await readFile(join(outDir, 'index.html'), 'utf8')).replace(STAMP, '')
  if (!html.includes('\n  </head>')) throw new Error('index.html: no "  </head>" line to stamp the build before')

  const assets = new Map<string, string>()
  let bytes = 0
  for (const path of paths) {
    if (path === 'index.html') continue
    const data = await readFile(join(outDir, path))
    assets.set(path, integrityOf(data))
    bytes += data.length
  }
  const hash = createHash('sha256')
  for (const [path, integrity] of assets) hash.update(`${path} ${integrity}\n`)
  const build = hash.update(html).digest('hex').slice(0, 16)

  const stamped = html.replace('\n  </head>', `\n    <meta name="${BUILD_META_NAME}" content="${build}">\n  </head>`)
  await writeFile(join(outDir, 'index.html'), stamped)
  assets.set('index.html', integrityOf(Buffer.from(stamped)))
  bytes += Buffer.byteLength(stamped)

  const source = await readFile(join(root, 'src/workers/sw.ts'), 'utf8')
  const { code } = await transformWithOxc(source, 'sw.ts')
  const body = code.replace(/^export \{\};?\n/m, '')
  if (/^\s*(import|export)\b/m.test(body)) throw new Error('src/workers/sw.ts must stay a classic script (no imports)')
  const list = [...assets].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  await writeFile(
    join(outDir, 'sw.js'),
    `// Generated by scripts/pwa.ts from src/workers/sw.ts.\nconst BUILD = ${JSON.stringify(build)}\n` +
      `const ASSETS = ${JSON.stringify(list)}\n${body}`,
  )
  return { build, files: list.length, bytes }
}

/** The plugin: writes the worker after every production build. */
export function pwa(): Plugin {
  let root = ''
  let outDir = ''
  let log: (message: string) => void = () => undefined
  return {
    name: 'pianissimo:pwa',
    apply: 'build',
    configResolved(config) {
      root = config.root
      outDir = resolve(config.root, config.build.outDir)
      log = (message) => config.logger.info(message)
    },
    writeBundle: {
      order: 'post',
      sequential: true,
      async handler() {
        const { build, files, bytes } = await writeServiceWorker(root, outDir)
        log(`sw.js: build ${build}, ${files} files precached (${(bytes / 1e6).toFixed(2)} MB)`)
      },
    },
  }
}
